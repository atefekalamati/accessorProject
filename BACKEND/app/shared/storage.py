"""File storage behind an interface (ADR-009); the real provider adapter is OPS-07 (D10).

Keys are generated by the server (``uuid4().hex`` + extension) and validated again here,
so a key can never address a path outside the storage root.
"""

from __future__ import annotations

import os
import re
import uuid
from pathlib import Path
from typing import Final, Protocol

import anyio
from fastapi import Request

from app.core.config import MediaStorage, Settings

_KEY: Final = re.compile(r"^[0-9a-f]{32}\.(jpg|png|webp)$")


def new_storage_key(extension: str) -> str:
    key = f"{uuid.uuid4().hex}.{extension}"
    _check_key(key)
    return key


def _check_key(key: str) -> None:
    if _KEY.fullmatch(key) is None:
        raise ValueError(f"Invalid storage key: {key!r}")


class FileStorage(Protocol):
    async def save(self, key: str, data: bytes) -> None: ...

    async def delete(self, key: str) -> None:
        """Remove ``key``; a missing file is not an error."""
        ...

    def url(self, key: str) -> str: ...


class _PublicUrls:
    def __init__(self, base_url: str) -> None:
        self._base_url = base_url.rstrip("/")

    def url(self, key: str) -> str:
        _check_key(key)
        return f"{self._base_url}/{key}"


class LocalFileStorage(_PublicUrls):
    """Files under ``root``; written to a temp name in the same directory, then renamed."""

    def __init__(self, root: Path, base_url: str) -> None:
        super().__init__(base_url)
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        _check_key(key)
        path = (self.root / key).resolve()
        if path.parent != self.root:
            raise ValueError(f"Storage key escapes the root: {key!r}")
        return path

    async def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        await anyio.to_thread.run_sync(_write_atomic, path, data)

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await anyio.to_thread.run_sync(lambda: path.unlink(missing_ok=True))


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
    try:
        temp.write_bytes(data)
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


class InMemoryFileStorage(_PublicUrls):
    """Test and development double; files live in this process only."""

    def __init__(self, base_url: str) -> None:
        super().__init__(base_url)
        self.files: dict[str, bytes] = {}

    async def save(self, key: str, data: bytes) -> None:
        _check_key(key)
        self.files[key] = data

    async def delete(self, key: str) -> None:
        _check_key(key)
        self.files.pop(key, None)


def create_file_storage(settings: Settings) -> FileStorage:
    if settings.media_storage is MediaStorage.MEMORY:
        return InMemoryFileStorage(settings.media_public_base_url)
    return LocalFileStorage(settings.media_root, settings.media_public_base_url)


def get_file_storage(request: Request) -> FileStorage:
    storage: FileStorage = request.app.state.file_storage
    return storage
